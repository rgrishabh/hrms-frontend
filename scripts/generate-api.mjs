#!/usr/bin/env node
/**
 * API types from the backend's openapi.json.
 *   npm run api:generate          writes src/lib/api-schema.gen.ts and src/lib/api-routes.gen.ts
 *   npm run api:check             fails if the committed files differ from what the spec gives (CI runs this)
 * The spec comes from HRMS_OPENAPI (a path), or ../hrms-backend/openapi.json beside this checkout.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const spec = resolve(process.env.HRMS_OPENAPI ?? join(root, '../hrms-backend/openapi.json'));
if (!existsSync(spec)) { process.stderr.write(`No OpenAPI spec at ${spec}. Set HRMS_OPENAPI.\n`); process.exit(2); }
const bin = join(root, 'tools/lint/node_modules/.bin/openapi-typescript');
if (!existsSync(bin)) spawnSync('npm', ['--prefix', 'tools/lint', 'ci', '--no-audit', '--no-fund'], { cwd: root, stdio: 'inherit' });

const temp = join(mkdtempSync(join(tmpdir(), 'hrms-api-')), 'schema.ts');
const r = spawnSync(bin, [spec, '--output', temp, '--alphabetize'], { cwd: root, encoding: 'utf8' });
if (r.status !== 0) { process.stderr.write(r.stderr); process.exit(r.status ?? 1); }
const head = '// Generated by `npm run api:generate` from the backend\'s openapi.json. Do not edit.\n';
const schema = head + readFileSync(temp, 'utf8');

const doc = JSON.parse(readFileSync(spec, 'utf8'));
const METHODS = ['get', 'post', 'put', 'patch', 'delete'];
const hasResponse = (op) => Object.entries(op.responses ?? {}).some(([code, x]) => /^2/.test(code) && x.content);
const rows = Object.entries(doc.paths).flatMap(([path, item]) => METHODS.filter((m) => item[m]).map((m) => [m.toUpperCase(), path, hasResponse(item[m])]));
rows.sort((a, b) => `${a[1]} ${a[0]}`.localeCompare(`${b[1]} ${b[0]}`));
const routes = `${head}/** Every API route, for the contract test. Not imported by the app. [method, path, has a response schema] */\nexport const API_ROUTES: readonly (readonly [string, string, boolean])[] = [\n${rows.map((x) => `  ${JSON.stringify(x).replace(/"/g, "'")},`).join('\n')}\n];\n`;

const out = [['src/lib/api-schema.gen.ts', schema], ['src/lib/api-routes.gen.ts', routes]];
if (process.argv.includes('--check')) {
  const stale = out.filter(([f, text]) => !existsSync(join(root, f)) || readFileSync(join(root, f), 'utf8') !== text).map(([f]) => f);
  if (stale.length) { process.stderr.write(`API types are out of date with ${spec}: ${stale.join(', ')}. Run npm run api:generate.\n`); process.exit(1); }
  process.stdout.write(`API types match ${spec}: ${rows.length} routes, ${rows.filter((x) => x[2]).length} with a response schema.\n`);
} else {
  for (const [f, text] of out) writeFileSync(join(root, f), text);
  process.stdout.write(`Wrote API types: ${rows.length} routes, ${rows.filter((x) => x[2]).length} with a response schema.\n`);
}
